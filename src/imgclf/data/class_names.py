def class_name(label: int) -> str:
    """Return the flower name for a zero-based label."""
    if not 0 <= label < NUM_CLASSES:
        raise IndexError(f"label {label} out of range [0, {NUM_CLASSES})")
    return CLASS_NAMES[label]
